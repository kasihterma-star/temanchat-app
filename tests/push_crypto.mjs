import {webcrypto,generateKeyPairSync} from 'node:crypto';
import assert from 'node:assert/strict';
import {_pushCryptoTest as h} from '../src/push.js';
const crypto=webcrypto;
const encoder=new TextEncoder();
const c=(...a)=>{const n=new Uint8Array(a.reduce((t,x)=>t+x.length,0));let i=0;for(const x of a){n.set(x,i);i+=x.length}return n};
const mac=async(k,x)=>new Uint8Array(await crypto.subtle.sign('HMAC',await crypto.subtle.importKey('raw',k,{name:'HMAC',hash:'SHA-256'},false,['sign']),x));
const expand=async(k,info,n)=>(await mac(k,c(info,new Uint8Array([1])))).slice(0,n);
const receiver=await crypto.subtle.generateKey({name:'ECDH',namedCurve:'P-256'},true,['deriveBits']);
const pub=new Uint8Array(await crypto.subtle.exportKey('raw',receiver.publicKey));
const auth=crypto.getRandomValues(new Uint8Array(16));
const raw=h.encryptedPayload({p256dh:h.b64url(pub),auth:h.b64url(auth)},{title:'Hello',body:'Push test'});
const data=await raw; const salt=data.slice(0,16),rs=new DataView(data.buffer).getUint32(16),l=data[20],serverPub=data.slice(21,21+l),cipher=data.slice(21+l);
assert.equal(l,65);assert.equal(rs,4096);
const remote=await crypto.subtle.importKey('raw',serverPub,{name:'ECDH',namedCurve:'P-256'},false,[]);
const shared=new Uint8Array(await crypto.subtle.deriveBits({name:'ECDH',public:remote},receiver.privateKey,256));
const ikm=await expand(await mac(auth,shared),c(encoder.encode('WebPush: info'),new Uint8Array([0]),pub,serverPub),32);
const prk=await mac(salt,ikm);
const cek=await expand(prk,c(encoder.encode('Content-Encoding: aes128gcm'),new Uint8Array([0])),16);
const nonce=await expand(prk,c(encoder.encode('Content-Encoding: nonce'),new Uint8Array([0])),12);
const clear=new Uint8Array(await crypto.subtle.decrypt({name:'AES-GCM',iv:nonce},await crypto.subtle.importKey('raw',cek,'AES-GCM',false,['decrypt']),cipher));
assert.equal(clear.at(-1),2);assert.deepEqual(JSON.parse(new TextDecoder().decode(clear.slice(0,-1))),{title:'Hello',body:'Push test'});
const vapid=generateKeyPairSync('ec',{namedCurve:'prime256v1'});const jwk=vapid.privateKey.export({format:'jwk'}),publicJwk=vapid.publicKey.export({format:'jwk'});
const publicKey=h.b64url(c(new Uint8Array([4]),h.from64(jwk.x),h.from64(jwk.y)));
const jwt=await h.vapidJwt({VAPID_PUBLIC_KEY:publicKey,VAPID_PRIVATE_KEY:jwk.d},'https://fcm.googleapis.com/fcm/send/sample');
const segments=jwt.split('.');assert.equal(segments.length,3);assert.equal(h.from64(segments[2]).length,64);
const verified=await crypto.subtle.verify({name:'ECDSA',hash:'SHA-256'},await crypto.subtle.importKey('jwk',publicJwk,{name:'ECDSA',namedCurve:'P-256'},false,['verify']),h.from64(segments[2]),encoder.encode(segments[0]+'.'+segments[1]));
assert.equal(verified,true);console.log('PASS: RFC8291 decrypt and VAPID jwt verified');
